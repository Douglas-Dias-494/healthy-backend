-- Initial schema: mirrors what Hibernate (ddl-auto=update) had been generating.
-- Databases that already existed are baselined at this version; new ones run this file.
-- Never edit an applied migration: add a new one (V3, V4...).

CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crm           VARCHAR(40),
    email         VARCHAR(100) NOT NULL,
    especialidade VARCHAR(60),
    nome          VARCHAR(100) NOT NULL,
    perfil        ENUM('MEDICO', 'PACIENTE') NOT NULL,
    senha_hash    VARCHAR(100) NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

-- Old shape of this table (no link to usuarios). Reworked in V2; it was empty.
CREATE TABLE patients (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    birth       TIMESTAMP(6) NOT NULL,
    cpf         VARCHAR(11) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    second_name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_patients_cpf UNIQUE (cpf)
);

CREATE TABLE appointments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_date DATE NOT NULL,
    location         VARCHAR(200) NOT NULL,
    reason           VARCHAR(200) NOT NULL,
    doctor_id        BIGINT NOT NULL,
    patient_id       BIGINT NOT NULL,
    CONSTRAINT fk_appointments_doctor FOREIGN KEY (doctor_id) REFERENCES usuarios (id),
    CONSTRAINT fk_appointments_patient FOREIGN KEY (patient_id) REFERENCES usuarios (id)
);

CREATE TABLE prescriptions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_date DATE NOT NULL,
    notes             VARCHAR(1000),
    doctor_id         BIGINT NOT NULL,
    patient_id        BIGINT NOT NULL,
    CONSTRAINT fk_prescriptions_doctor FOREIGN KEY (doctor_id) REFERENCES usuarios (id),
    CONSTRAINT fk_prescriptions_patient FOREIGN KEY (patient_id) REFERENCES usuarios (id)
);

CREATE TABLE prescription_items (
    prescription_id BIGINT NOT NULL,
    position        INTEGER NOT NULL,
    dosage          VARCHAR(50) NOT NULL,
    instructions    VARCHAR(300) NOT NULL,
    name            VARCHAR(100) NOT NULL,
    quantity        INTEGER NOT NULL,
    PRIMARY KEY (prescription_id, position),
    CONSTRAINT ck_prescription_items_position CHECK (position >= 0),
    CONSTRAINT fk_prescription_items_prescription FOREIGN KEY (prescription_id) REFERENCES prescriptions (id)
);

CREATE TABLE medication_trackings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dosage             VARCHAR(50) NOT NULL,
    medication_name    VARCHAR(100) NOT NULL,
    remaining_quantity INTEGER NOT NULL,
    start_date         DATE NOT NULL,
    total_quantity     INTEGER NOT NULL,
    version            BIGINT NOT NULL,
    patient_id         BIGINT NOT NULL,
    prescription_id    BIGINT NOT NULL,
    CONSTRAINT uk_trackings_patient_prescription_medication UNIQUE (patient_id, prescription_id, medication_name),
    CONSTRAINT fk_trackings_patient FOREIGN KEY (patient_id) REFERENCES usuarios (id),
    CONSTRAINT fk_trackings_prescription FOREIGN KEY (prescription_id) REFERENCES prescriptions (id)
);
