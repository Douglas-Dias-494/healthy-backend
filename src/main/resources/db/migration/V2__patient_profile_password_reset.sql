-- 1) Versão dos tokens do usuário. O JWT carrega a versão com que nasceu; trocar a senha soma 1 aqui,
--    e todos os tokens antigos deixam de valer. (Tokens sem a informação contam como versão 0.)
ALTER TABLE usuarios ADD COLUMN token_version INTEGER DEFAULT 0 NOT NULL;

-- 2) Perfil clínico do paciente passa a pertencer a um usuário.
--    O nome vive em usuarios.nome (não se repete aqui). A tabela antiga estava vazia, então é recriada.
DROP TABLE patients;
CREATE TABLE patients (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    cpf        VARCHAR(11) NOT NULL,
    birth_date DATE NOT NULL,
    phone      VARCHAR(20),
    CONSTRAINT uk_patients_usuario UNIQUE (usuario_id),
    CONSTRAINT uk_patients_cpf UNIQUE (cpf),
    CONSTRAINT fk_patients_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

-- 3) Recuperação de senha. Só o HASH do token é guardado: quem lê o banco não consegue usar os links.
CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_password_reset_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_password_reset_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

-- 4) O mesmo atendimento (médico + paciente + data) não pode ser registrado duas vezes.
ALTER TABLE appointments
    ADD CONSTRAINT uk_appointments_doctor_patient_date UNIQUE (doctor_id, patient_id, appointment_date);
